# ===========================================================================
# ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ
# ===========================================================================
def interpolate_table(pressure_mmhg: float, table: list[tuple[float, float, float]]) -> tuple[float, float]:
    """Линейная интерполяция по таблице (давление -> (A, B)).

    Границы диапазона ВКЛЮЧАЮТСЯ (возвращают крайние строки таблицы):
    pressure == table[0][0] -> первая строка; pressure == table[-1][0] -> последняя.
    Вне диапазона таблицы — ValueError (вызывающий код решает, что делать).
    """
    if pressure_mmhg < table[0][0] or pressure_mmhg > table[-1][0]:
        raise ValueError(f"Давление {pressure_mmhg} вне диапазона таблицы [{table[0][0]}, {table[-1][0]}]")
    for i in range(len(table) - 1):
        p0, a0, b0 = table[i]
        p1, a1, b1 = table[i + 1]
        if p0 <= pressure_mmhg <= p1:
            if p1 == p0:
                return a0, b0
            t = (pressure_mmhg - p0) / (p1 - p0)
            return a0 + t * (a1 - a0), b0 + t * (b1 - b0)
    raise ValueError(f"Невозможно интерполировать давление {pressure_mmhg}")


